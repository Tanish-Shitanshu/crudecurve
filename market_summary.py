"""
market_summary.py — A short written summary of the market, generated by
fixed rules from the computed metrics. No model, no randomness: the same
numbers always produce the same text, and every number in the text comes
from the metrics dictionary (see metrics.build_metrics).
"""

from config import RECENT_WINDOW_DAYS
from formatting import format_pct, format_signed_usd, format_usd

LIMITATIONS = (
    "Limitations: unofficial, delayed Yahoo Finance daily closes; VaR is historical "
    "simulation and assumes the past is representative of the future; roll days are "
    "excluded from returns; the roll-window figure is a proxy, not a true roll yield; "
    "not investment advice."
)

# If the last-12-months VaR differs from the selected-window VaR by more
# than this fraction, the summary says recent risk is higher or lower.
_RECENT_DIFFERENCE = 0.20


def _regime_meaning(label: str) -> str:
    """One sentence explaining what the regime label means."""
    if label.startswith("Backwardation"):
        return "Backwardation means nearer delivery costs more than later delivery."
    if label.startswith("Contango"):
        return ("Contango means later delivery costs more than nearer delivery, "
                "which usually reflects storage and financing costs.")
    if label.startswith("Kinked"):
        return ("The curve changes direction along its length, so the front-to-back "
                "figure is only the net effect.")
    if label == "Flat":
        return "Front and back prices are nearly equal."
    return "There are not enough contracts to classify the curve."


def _recent_comparison(selected: dict, recent: dict) -> str:
    """
    Compare the last-12-months VaR with the selected-window VaR at both
    confidence levels (each argument maps confidence -> VaR dict). "Higher"
    wins if either level is clearly higher, because understating risk is
    the costly mistake.
    """
    ratios = [recent[c]["var_pct"] / selected[c]["var_pct"] for c in selected]
    if any(ratio > 1 + _RECENT_DIFFERENCE for ratio in ratios):
        return ("Recent risk is higher than the longer window suggests, so the longer-window "
                "figure may understate current risk.")
    if all(ratio < 1 - _RECENT_DIFFERENCE for ratio in ratios):
        return "Recent risk is lower than the longer window suggests."
    return "Recent risk is similar to the longer window."


def build_market_summary(m: dict) -> str:
    """Build the summary paragraph from a metrics dictionary."""
    sentences = [
        f"As of {m['as_of']}, the WTI futures curve is in {m['label']}: the front contract "
        f"({m['front_ticker']}) is {format_usd(m['front_price'])} per barrel and the "
        f"{m['back_ticker']} contract is {format_usd(m['back_price'])}, an annualised "
        f"front-to-back spread of {format_pct(m['annualised_carry_pct'], signed=True)}.",
        _regime_meaning(m["label"]),
    ]

    roll_word = "gain" if m["roll_gain_per_year"] >= 0 else "cost"
    contracts = f"{m['n_contracts']} contract{'s' if m['n_contracts'] != 1 else ''}"
    sentences.append(
        f"For a long position of {contracts} (notional {format_usd(m['notional'], 0)}), "
        f"the current curve implies a roll {roll_word} of about "
        f"{format_usd(abs(m['roll_gain_per_year']), 0)} per year if it stays unchanged."
    )
    sentences.append(
        f"Over the last two years the roll-window proxy is "
        f"{format_signed_usd(m['roll_window_proxy'])} per barrel."
    )

    risk = m["risk"]
    var95, recent95 = risk["var"][0.95], risk["var_recent"][0.95]
    var99, recent99 = risk["var"][0.99], risk["var_recent"][0.99]
    if var95["var_pct"] is None:
        sentences.append("Risk figures are unavailable because price history could not be loaded.")
    else:
        sentences.append(
            f"Historical 1-day 95% VaR is {format_usd(var95['var_usd'], 0)} "
            f"({format_pct(var95['var_pct'] * 100)} of notional) over the last "
            f"{m['lookback_years']} years ({var95['observations']} observations); over the last "
            f"{RECENT_WINDOW_DAYS // 30} months it is {format_usd(recent95['var_usd'], 0)}. "
            f"At 99% the figures are {format_usd(var99['var_usd'], 0)} and {format_usd(recent99['var_usd'], 0)} "
            f"({recent99['observations']} recent observations, so the 99% figure is rough). "
            + _recent_comparison(risk["var"], risk["var_recent"])
        )
        sentences.append(
            f"Latest 21-day annualised volatility is {format_pct(risk['volatility'] * 100, 1)} and the "
            f"maximum drawdown over the window was "
            f"{format_pct(risk['max_drawdown']['max_drawdown'] * 100, 1)}."
        )

    if m["source"] == "snapshot":
        sentences.append("Note: this uses a saved snapshot, not live data.")

    return " ".join(sentences)
